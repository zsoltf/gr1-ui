#!/usr/bin/env python3
"""Generate fixed-width Rust ABI and stock defaults from pinned bytecode as data."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tempfile
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from inspect_firmware import inspect, MEMBER
from xdis.load import load_module
from xdis.bytecode import Bytecode
from xdis.op_imports import get_opcode_module


def defaults(instructions, start, stop, constants):
    stack = []
    names = dict(constants, __version__='3.4.4', np=('np',))
    for i in instructions:
        if not start <= i.offset < stop:
            continue
        op, v = i.opname, i.argval
        if op == 'BUILD_MAP':
            stack.append({})
        elif op == 'LOAD_CONST' and isinstance(v, (str, int, float, bool)):
            stack.append(v)
        elif op == 'LOAD_NAME':
            stack.append(names[v])
        elif op == 'LOAD_ATTR' and stack[-1] == ('np',) and v in ('zeros', 'float32'):
            stack[-1] = ('np', v)
        elif op == 'CALL_FUNCTION' and v == 257:
            dtype, key, count, fn = (stack.pop() for _ in range(4))
            if fn != ('np', 'zeros') or key != 'dtype' or dtype != ('np', 'float32'):
                raise ValueError('unexpected default array expression')
            stack.append([0.0] * count)
        elif op == 'STORE_MAP':
            key, value = stack.pop(), stack.pop()
            stack[-1][key] = value
        elif op == 'BUILD_LIST':
            values = stack[-v:]
            del stack[-v:]
            stack.append(values)
        elif op == 'BINARY_MULTIPLY':
            right, left = stack.pop(), stack.pop()
            stack.append(left * right)
        elif op == 'UNARY_NEGATIVE':
            stack[-1] = -stack[-1]
        else:
            raise ValueError(f'unsupported default instruction {i.offset} {op}')
    if len(stack) != 1 or not isinstance(stack[0], dict):
        raise ValueError('incomplete defaults')
    return stack[0]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('firmware', type=Path)
    p.add_argument('--out', type=Path, default=Path('ui/src/device'))
    a = p.parse_args()
    metadata = inspect(a.firmware)
    constants = metadata['constants']
    with tarfile.open(a.firmware) as t, tempfile.TemporaryDirectory() as tmp:
        file = Path(tmp) / 'gui.pyo'
        file.write_bytes(t.extractfile(MEMBER).read())
        version, _, _, code, *_ = load_module(str(file))
    instructions = list(Bytecode(code, get_opcode_module(version, 'CPython')))
    patch = defaults(instructions, 1697, 2572, constants)
    system = defaults(instructions, 2684, 2862, constants)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / 'defaults.json').write_text(json.dumps({'patch': patch, 'system': system}, indent=2) + '\n')
    lines = ['// Generated by tools/device/generate.py. Do not hand edit.\n',
             '// Firmware SHA-256: ' + metadata['firmware_sha256'] + '\n',
             '#![allow(dead_code)]\n']
    types = {'c_float': 'f32', 'c_int': 'i32', 'c_char': 'u8', 'StructMultiPreset': 'Multi'}
    def rust_type(typ):
        if typ in types:
            return types[typ]
        m = re.fullmatch(r'\((\w+) \* (\w+)\)', typ)
        if not m:
            raise ValueError(typ)
        name, n = m.groups()
        return f'[{types[name]}; {int(n) if n.isdecimal() else constants[n]}]'
    for name in ('StructMultiPreset', 'IPC'):
        struct = 'Multi' if name == 'StructMultiPreset' else 'Ipc'
        fields = metadata['structures'][name]['fields']
        lines += ['#[repr(C)]\n#[derive(Clone, Copy, Debug, PartialEq)]\n', f'pub struct {struct} {{\n']
        lines += [f'    pub {f["name"]}: {rust_type(f["type"])},\n' for f in fields]
        lines += ['}\n', f'impl Default for {struct} {{\n    fn default() -> Self {{\n',
                  '        // All fields are numbers/byte arrays; all-zero is a valid bit pattern.\n',
                  '        unsafe { std::mem::zeroed() }\n    }\n}\n']
        if name == 'IPC':
            numeric = [f for f in fields if f['type'] in ('c_float', 'c_int')]
            lines += ['impl Ipc {\n    pub fn number(&self, key: &str) -> Option<f32> {\n        Some(match key {\n']
            lines += [f'            "{f["name"]}" => self.{f["name"]} as f32,\n' for f in numeric]
            lines += ['            _ => return None,\n        })\n    }\n',
                      '    pub fn set_number(&mut self, key: &str, value: f32) -> bool {\n        match key {\n']
            lines += [f'            "{f["name"]}" => self.{f["name"]} = value as {rust_type(f["type"])},\n' for f in numeric]
            lines += ['            _ => return false,\n        }\n        true\n    }\n}\n']
            lines += ['pub const PATCH_FIELDS: &[&str] = &[\n']
            lines += [f'    "{f["name"]}",\n' for f in numeric if f['name'] in patch]
            lines += ['];\n']
    for name, value in sorted(constants.items()):
        if isinstance(value, int):
            lines += [f'pub const {name}: i32 = {value};\n']
    lines += ['const _: [(); 6752] = [(); std::mem::size_of::<Ipc>()];\n',
              'const _: [(); 308] = [(); std::mem::size_of::<Multi>()];\n',
              'const _: [(); 4] = [(); std::mem::align_of::<Ipc>()];\n']
    # Independent anchors recovered from the native copy/access instructions;
    # not inferred from this generated field list.
    for field, offset in {'name': 0x30, 'sample': 0x130, 'mod_matrix': 0x2b8,
                          'aux_buf': 0x4cc, 'western_scale': 0x14d8,
                          'multi_presets': 0x158c, 'current_multi_preset': 0x1a5c}.items():
        lines += [f'const _: [(); {offset}] = [(); std::mem::offset_of!(Ipc, {field})];\n']
    (a.out / 'abi.rs').write_text(''.join(lines))
    subprocess.run(['rustfmt', '--edition', '2021', str(a.out / 'abi.rs')], check=True)
    print('Generated two fixed-width structures and', len(patch), 'patch defaults.')

if __name__ == '__main__':
    main()
